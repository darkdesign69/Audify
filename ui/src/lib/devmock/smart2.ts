let smart: SmartShuffleState = { on: false, sourceId: null, recIds: [] };

export function smart2Handlers(emit: (event: string, payload: unknown) => void, emitQueue: () => void) {
	const setSmart = (s: SmartShuffleState) => {
		smart = s;
		emit('smart-shuffle-changed', s);
		return s;
	};
	const dropRecs = () => {
		const ids = new Set(smart.recIds);
		player.items = player.items.filter((s, i) => i <= player.current || !ids.has(s.video_id));
	};
	return {
		made_for_you: () => mfyCards(),
		whats_new: () => whatsNew(),
		whats_new_count: () => whatsNew().newCount,
		whats_new_mark_seen: () => {
			seenAt = NOW + 1;
			emit('whats-new-changed', { newCount: 0 });
		},
		smart_shuffle_state: () => smart,
		smart_shuffle_set: (a: any) => {
			dropRecs();
			if (!a.on) {
				player.shuffle = false;
				emitQueue();
				return setSmart({ on: false, sourceId: null, recIds: [] });
			}
			const src = player.sourceId ?? '';
			if (!(src.startsWith('LOCALPLAYLIST:') || src === 'VLLM')) throw 'Smart Shuffle works in your own playlists';
			player.shuffle = true;
			const have = new Set(player.items.map((s) => s.video_id));
			let recs = [...((fx.search_songs_daft_punk as SongItem[] | undefined) ?? []), ...poolSlice(40, 30)].filter(
				(s) => !have.has(s.video_id)
			);
			// The fixture pool is small: stand-ins with their own ids when the playlist holds it all.
			if (recs.length < 10) recs = poolSlice(7, 20).map((s) => ({ ...s, video_id: `${s.video_id}~rec` }));
			const ids: string[] = [];
			let at = player.current + 1;
			let run = 0;
			let r = 0;
			while (at < player.items.length && r < recs.length) {
				run++;
				at++;
				if (run === 3) {
					player.items.splice(at, 0, { ...recs[r] });
					ids.push(recs[r].video_id);
					at++;
					r++;
					run = 0;
				}
			}
			emitQueue();
			return setSmart({ on: true, sourceId: src, recIds: ids });
		},
		smart_shuffle_remove: (a: any) => {
			player.items = player.items.filter((s, i) => i <= player.current || s.video_id !== a.videoId);
			emitQueue();
			return setSmart({ ...smart, recIds: smart.recIds.filter((i) => i !== a.videoId) });
		},
		smart_shuffle_keep: (a: any) => setSmart({ ...smart, recIds: smart.recIds.filter((i) => i !== a.videoId) })
	};
}
