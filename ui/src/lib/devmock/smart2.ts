function whatsNew(): WhatsNew {
	const albums: any[] = (fx.new_releases?.sections ?? []).flatMap((s: any) => s.items).filter((i: any) => i.kind === 'album');
	const music: WhatsNewRelease[] = albums.slice(0, 8).map((al: any, i: number) => {
		const firstSeen = i < 3 ? NOW - i * 20_000 : i < 6 ? NOW - (i + 2) * 86_400 : 0;
		const run = al.artistRuns?.find((r: any) => r.id) ?? al.artist_runs?.find((r: any) => r.id);
		return {
			id: al.id,
			title: al.title,
			subtitle: al.subtitle,
			thumbnail: al.thumbnail,
			artist: run?.text ?? String(al.subtitle ?? '').split(' • ').pop() ?? '',
			artistId: run?.id ?? 'UCdaftpunk',
			year: 2026,
			firstSeen,
			followed: true,
			ytNew: i < 3,
			position: i,
			releaseType: /single/i.test(al.subtitle ?? '') ? 'Single' : /\bEP\b/.test(al.subtitle ?? '') ? 'EP' : 'Album',
			isNew: firstSeen > seenAt
		};
	});
	const podcasts = allEpisodes()
		.slice(0, 6)
		.map((e: any) => ({ ...e, isNew: (e.publishedAt ?? 0) > seenAt }));
	const newCount = music.filter((m) => m.isNew).length + podcasts.filter((p: any) => p.isNew).length;
	return { music, podcasts, seenAt, newCount };
}

