/** The cover the backend writes (mfy.rs::cover_svg, one layout, same Figtree outlines), without
 *  the photo: an SVG in an <img> can't load one from the web (the app embeds it as base64). */
export function coverSvg(label: string, n: number): string {
	const body = backdrop(BANDS[n % BANDS.length]) + MARK + textPaths(label, 28, 600, fit(label, 584, 64), '#fff');
	const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 640"><defs><radialGradient id="glow" cx="0.75" cy="0.2" r="0.9"><stop offset="0" stop-color="#fff" stop-opacity="0.28"/><stop offset="1" stop-color="#000" stop-opacity="0.25"/></radialGradient></defs>${body}</svg>`;
	return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

